"""Tests for the Kim tuning discipline in train_disturbance_clf.py.

Run:  ~/workspace/.mlvenv/bin/python test_kim_tuning.py
       (no pytest needed; needs scikit-learn, like the trainer)

Contract under test (Kim et al., arXiv:2505.04085v2):
  * Elastic Net alpha and path-thickness gamma are tuned by
    OPTIMIZATION ON DATA (grid search over candidates, scored
    against known target positions) -- never hand-picked;
  * DBSCAN on the binarized image extracts blobs (isolated hot
    pixels are noise, not detections);
  * tuned values are LOGGED PER DEPLOYMENT with data provenance
    attached, and provenance is required, not defaulted;
  * detection thresholds are SIZE-AWARE (slim targets degrade
    per Kim et al. -- smaller fraction for smaller targets);
  * the 6-node / 15-link ~1-2 m imaging bound is NOT upgraded
    here: the harness scenes below are generated by this file's
    own forward model, so good harness scores are a MACHINERY
    CHECK ONLY -- they are harness-generated, NOT field data, and
    no test here asserts field accuracy.
"""
