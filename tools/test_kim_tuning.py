def test_score_blobs_empty_scene_scores_zero():
    # S6: no blobs + no truth is a correct empty answer (0.0),
    # not -20 -- the old formula scored it WORSE than one
    # phantom blob (-1), inverting the case the scorer rewards.
    assert t.score_blobs([], []) == 0.0
    assert t.score_blobs([], []) > t.score_blobs(
        [{"centroid_xy": [5.0, 4.0], "pixel_count": 4,
          "bbox_rows": [0, 1], "bbox_cols": [0, 1]}], [])
    # Non-empty cases unchanged: a miss still scores -21.
    assert t.score_blobs([], [[5.0, 4.0]]) == -21.0


def test_binarize_image_size_aliases_and_validation():
    # F9: Dart S/M/L normalize onto small/medium/large, and the
    # binarization ordering holds across both vocabularies.
    img = np.array([1.0, 0.35, 0.0])
    assert t.binarize_image(img, "S")[1]      # == small
    assert not t.binarize_image(img, "L")[1]  # == large
    assert t.binarize_image(img, "small")[1]
    assert (t.binarize_image(img, "M").tolist()
            == t.binarize_image(img, "medium").tolist())
    assert (t.binarize_image(img, "s").tolist()
            == t.binarize_image(img, "small").tolist())
    # S7/F9: an unknown size raises a clear ValueError naming
    # the accepted values -- never a bare KeyError.
    for bad in ("XL", "huge", "", None, 3):
        try:
            t.binarize_image(img, bad)
            raise AssertionError(f"size_class {bad!r} must raise")
        except ValueError as e:
            assert "small" in str(e) and "S/M/L" in str(e), e
    # S7: frac must satisfy 0 < frac <= 1 -- frac <= 0 used to
    # make the whole grid True.
    for bad_frac in (0.0, -0.5, 1.5, float("nan")):
        try:
            t.binarize_image(img, "medium", frac=bad_frac)
            raise AssertionError(f"frac {bad_frac!r} must raise")
        except ValueError:
            pass
    assert t.binarize_image(img, "medium", frac=1.0)[0]
    assert not t.binarize_image(img, "medium", frac=1.0)[1]


def test_dbscan_blobs_validates_lengths():
    # S7: a binary/pixel_xy length mismatch raises a clear
    # ValueError up front, not an opaque reshape/IndexError.
    grid = (2, 2)
    pixels = [(float(c), float(r)) for r in range(2) for c in range(2)]
    binary = np.zeros(4, dtype=bool)
    binary[0] = binary[1] = binary[2] = True  # L-shape: 3 pixels,
    # each within eps of the other two, so all three are core
    # points (min_samples=3 counts neighbours incl. itself).
    try:
        t.dbscan_blobs(np.zeros(3, dtype=bool), grid, pixels)
        raise AssertionError("short binary must raise")
    except ValueError as e:
        assert "binary_img" in str(e), e
    try:
        t.dbscan_blobs(binary, grid, pixels[:3])
        raise AssertionError("short pixel_xy must raise")
    except ValueError as e:
        assert "pixel_xy" in str(e), e
    try:
        t.dbscan_blobs(binary, (0, 2), pixels)
        raise AssertionError("bad grid_shape must raise")
    except ValueError:
        pass
    # Valid input unchanged: the 3-pixel L is one blob.
    blobs = t.dbscan_blobs(binary, grid, pixels)
    assert len(blobs) == 1 and blobs[0]["pixel_count"] == 3, blobs


def test_kim_cli_precedence_and_refusals():
    # Nit (d): --kim-tune-demo wins over --kim-tune when both
    # are passed (documented precedence), and the --kim-tune
    # refusal paths (no --kim-log, missing provenance) exit
    # non-zero with a clear message -- all pinned via the CLI.
    scenes = t.make_harness_scenes(n_scenes=4)
    data = {"nodes": scenes[0]["nodes"], "pixels": scenes[0]["pixels"],
            "grid_shape": list(scenes[0]["grid_shape"]),
            "provenance": "harness-generated, NOT field data",
            "scenes": [{"y": s["y"], "truth_xy": s["truth_xy"],
                        "size_class": s["size_class"]} for s in scenes]}
    data_no_prov = dict(data)
    data_no_prov.pop("provenance")
    with tempfile.TemporaryDirectory() as td:
        fpath = os.path.join(td, "scenes.json")
        with open(fpath, "w") as f:
            json.dump(data, f)
        nopath = os.path.join(td, "no_prov.json")
        with open(nopath, "w") as f:
            json.dump(data_no_prov, f)
        log = os.path.join(td, "kim_log.jsonl")
        # Refusal: --kim-tune without --kim-log.
        r = subprocess.run(
            [sys.executable, os.path.join(HERE, "train_disturbance_clf.py"),
             "--kim-tune", fpath],
            capture_output=True, text=True, timeout=300)
        assert r.returncode != 0 and "--kim-log" in r.stderr, r
        # Refusal: scenes file without a provenance field.
        r = subprocess.run(
            [sys.executable, os.path.join(HERE, "train_disturbance_clf.py"),
             "--kim-tune", nopath, "--kim-log", log],
            capture_output=True, text=True, timeout=300)
        assert r.returncode != 0 and "provenance" in r.stderr, r
        # Precedence: demo wins even when --kim-tune points at
        # a file that would refuse (no provenance) -- the demo
        # runs and exits 0, the tune path never loads.
        log2 = os.path.join(td, "demo_log.jsonl")
        r = subprocess.run(
            [sys.executable, os.path.join(HERE, "train_disturbance_clf.py"),
             "--kim-tune-demo", "--kim-tune", nopath,
             "--kim-log", log2],
            capture_output=True, text=True, timeout=300)
        assert r.returncode == 0, r.stderr[-2000:]
        assert "NOT field data" in r.stdout, r.stdout


