def test_weight_matrix_shape_and_gamma_effect():
    nodes = [(0.0, 0.0), (5.0, 0.0), (10.0, 0.0),
             (0.0, 8.0), (5.0, 8.0), (10.0, 8.0)]
    pixels = [(5.0, 4.0), (0.5, 0.5), (9.5, 7.5)]
    w_small = t.build_link_pixel_weights(nodes, pixels, 0.3)
    w_large = t.build_link_pixel_weights(nodes, pixels, 1.5)
    assert w_small.shape == (15, 3), w_small.shape  # 6 nodes -> 15 links
    assert w_large.shape == (15, 3)
    # Weights are in (0, 1]; a pixel exactly on a link line has
    # excess path 0 and weight 1 at any gamma. Pixel (5, 4) sits on
    # the (5, 0)-(5, 8) link, pair index 7 in i<j order.
    assert float(np.max(w_small[:, 0])) == 1.0
    assert float(w_small[7, 0]) == 1.0
    assert float(np.max(w_small)) <= 1.0
    # Off-link pixels gain weight as gamma grows (thicker ellipses).
    assert float(np.mean(w_large[:, 1:])) > float(np.mean(w_small[:, 1:]))
    try:
        t.build_link_pixel_weights(nodes, pixels, 0.0)
        raise AssertionError("gamma <= 0 must raise")
    except ValueError:
        pass


def test_dbscan_blobs_and_noise():
    # Two separated clusters -> 2 blobs; an isolated pixel -> noise.
    # 7x7 grid so the isolated centre pixel (3, 3) sits > eps (1.5)
    # from both clusters (nearest distance 2.83): with eps = 1.5,
    # diagonal neighbours (distance 1.414) DO chain, so a 5x5
    # layout would merge through the centre -- the geometry here
    # is chosen to test separation honestly.
    grid = (7, 7)
    pixels = [(float(c), float(r)) for r in range(7) for c in range(7)]
    binary = np.zeros(49, dtype=bool)
    for idx in (0, 1, 7, 8):        # top-left 2x2 cluster
        binary[idx] = True
    for idx in (40, 41, 47, 48):    # bottom-right 2x2 cluster
        binary[idx] = True
    binary[24] = True                # isolated centre pixel: noise
    blobs = t.dbscan_blobs(binary, grid, pixels)
    assert len(blobs) == 2, blobs
    assert sorted(b["pixel_count"] for b in blobs) == [4, 4]
    assert t.dbscan_blobs(np.zeros(49, dtype=bool), grid, pixels) == []
    lone = np.zeros(49, dtype=bool)
    lone[24] = True
    assert t.dbscan_blobs(lone, grid, pixels) == []


def test_size_aware_binarize_ordering():
    assert (t.SIZE_BINARIZE_FRAC["small"]
            < t.SIZE_BINARIZE_FRAC["medium"]
            < t.SIZE_BINARIZE_FRAC["large"])
    # A weak (slim-target-like) cell at 0.35 of max: invisible to
    # the "large" fraction, visible to the "small" fraction -- the
    # size-aware caveat in action, at the cost of more false pixels.
    img = np.array([1.0, 0.35, 0.0])
    assert not t.binarize_image(img, "large")[1]
    assert t.binarize_image(img, "small")[1]
    assert not t.binarize_image(np.zeros(3), "small").any()


def test_score_blobs_bounded_and_exact():
    assert t.score_blobs([], [[5.0, 4.0]]) == -21.0  # bounded miss
    blob = {"centroid_xy": [5.0, 4.0], "pixel_count": 4,
            "bbox_rows": [0, 1], "bbox_cols": [0, 1]}
    assert t.score_blobs([blob], [[5.0, 4.0]]) == 0.0
    # A phantom second blob costs exactly the count penalty.
    blob2 = dict(blob, centroid_xy=[9.0, 7.0])
    assert t.score_blobs([blob, blob2], [[5.0, 4.0]]) == -1.0


def test_kim_tuning_run_on_harness_scenes():
    # HARNESS-GENERATED scenes (NOT field data) -- this run proves
    # the tuning machinery works end to end, nothing more.
    scenes = t.make_harness_scenes(n_scenes=12)
    assert len(scenes) == 12 and len(scenes[0]["y"]) == 15
    best = t.tune_kim_params(scenes)
    assert best["alpha"] in t.KIM_DEFAULT_ALPHAS
    assert best["gamma"] in t.KIM_DEFAULT_GAMMAS
    assert len(best["grid"]) == len(t.KIM_DEFAULT_ALPHAS) * len(
        t.KIM_DEFAULT_GAMMAS)
    assert best["score"] == max(g["score"] for g in best["grid"])
    # The grid search recovers the harness forward-model gamma
    # (0.6) -- the machinery can find the parameter that generated
    # the data, which is the minimum bar for a tuning procedure.
    assert best["gamma"] == 0.6, best
    assert best["score"] > -1.0, best  # mean centroid error < ~1 m
    # Per-scene: reconstruction + binarize + DBSCAN finds one blob
    # near truth on the harness (machinery check, NOT field claim).
    W = t.build_link_pixel_weights(scenes[0]["nodes"],
                                   scenes[0]["pixels"], best["gamma"])
    img = t.elastic_net_reconstruct(W, scenes[0]["y"], best["alpha"])
    blobs = t.dbscan_blobs(
        t.binarize_image(img, "medium"), scenes[0]["grid_shape"],
        scenes[0]["pixels"])
    assert len(blobs) >= 1, blobs
    tx, ty = scenes[0]["truth_xy"][0]
    err = min(math.hypot(b["centroid_xy"][0] - tx,
                         b["centroid_xy"][1] - ty) for b in blobs)
    assert err < 1.0, (err, blobs)


