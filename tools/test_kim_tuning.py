        r = subprocess.run(
            [sys.executable,
             os.path.join(HERE, "train_disturbance_clf.py"),
             "--kim-tune", fpath, "--kim-log", log,
             "--kim-deployment", "round-trip-site"],
            capture_output=True, text=True, timeout=300)
        assert r.returncode == 0, r.stderr[-2000:]
        with open(log) as f:
            rec = json.loads(f.readline())
        assert rec["deployment"] == "round-trip-site"
        assert rec["data_provenance"] == "harness-generated, NOT field data"
        # ...and --kim-tune-demo runs standalone and logs the demo
        # provenance (NOT field data) when given a log path.
        log2 = os.path.join(td, "demo_log.jsonl")
        r = subprocess.run(
            [sys.executable,
             os.path.join(HERE, "train_disturbance_clf.py"),
             "--kim-tune-demo", "--kim-log", log2],
            capture_output=True, text=True, timeout=300)
        assert r.returncode == 0, r.stderr[-2000:]
