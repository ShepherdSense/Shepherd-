/*
 * Host C++ test for the Shepherd LoRa codec v2 — compiles the REAL
 * shared header (esp32/shepherd_lora_psk/src/lora_psk_codec.h, the
 * exact code both sketches ship) and runs it against the frozen
 * vectors in lora_psk_vectors.json:
 *
 *   * wrap() output equals the frozen wire34, byte for byte;
 *   * unwrap() accepts the frozen wire34 and rebuildV1() reproduces
 *     the frozen plain22 exactly;
 *   * unwrap() rejects a wrong PSK and single-bit tampering at the
 *     schema byte (AAD), nonce, ciphertext, and tag offsets.
 *
 * The header's mbedTLS calls resolve to the test double in stub/
 * (see stub/mbedtls/ccm.h for why, and for how the double itself is
 * anchored). Before touching the codec vectors, this test anchors the
 * double directly to RFC 3610 test vector #1 — the same published
 * known answer the Python reference (aes_ccm.py) is anchored to.
 *
 * Build & run:  ./run_cpp_tests.sh        (from this folder)
 * Exit code 0 = all checks passed.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <string>
#include <vector>
#include <fstream>
#include <sstream>

#include "lora_psk_codec.h"   // the real shared header under test
#include "mbedtls/ccm.h"      // stub API, for the RFC 3610 anchor check

static int failures = 0;
static int checks = 0;
#define CHECK(cond, ...)                                       \
  do {                                                         \
    checks++;                                                  \
    if (!(cond)) {                                             \
      failures++;                                              \
      printf("FAIL %s:%d: ", __FILE__, __LINE__);              \
      printf(__VA_ARGS__);                                     \
      printf("\n");                                            \
    }                                                          \
  } while (0)

// ---------- tiny frozen-JSON extraction (no external deps) ----------
// The vectors file is generated by make_vectors.py with a stable
// shape; we only need string/integer fields by name.

static std::string slurp(const char *path) {
  std::ifstream in(path, std::ios::binary);
  if (!in) { fprintf(stderr, "cannot open %s\n", path); exit(2); }
  std::stringstream ss; ss << in.rdbuf();
  return ss.str();
}

// Value of "key": "...." searching from pos; returns npos-based "".
static std::string jsonStr(const std::string &doc, const char *key, size_t from = 0) {
  std::string pat = std::string("\"") + key + "\"";
  size_t k = doc.find(pat, from);
  if (k == std::string::npos) return "";
  size_t q1 = doc.find('"', k + pat.size());
  size_t q2 = (q1 == std::string::npos) ? q1 : doc.find('"', q1 + 1);
  if (q1 == std::string::npos || q2 == std::string::npos) return "";
  return doc.substr(q1 + 1, q2 - q1 - 1);
}

static long jsonInt(const std::string &doc, const char *key, size_t from = 0) {
  std::string pat = std::string("\"") + key + "\"";
  size_t k = doc.find(pat, from);
  if (k == std::string::npos) return -1;
  size_t c = doc.find(':', k + pat.size());
  if (c == std::string::npos) return -1;
  return strtol(doc.c_str() + c + 1, nullptr, 10);
}

static std::vector<uint8_t> unhex(const std::string &h) {
  std::vector<uint8_t> out;
  auto hv = [](char c) -> int {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
  };
  for (size_t i = 0; i + 1 < h.size(); i += 2)
    out.push_back((uint8_t)((hv(h[i]) << 4) | hv(h[i + 1])));
  return out;
}

static std::string hexOf(const uint8_t *p, size_t n) {
  std::string s;
  char b[3];
  for (size_t i = 0; i < n; i++) { snprintf(b, sizeof(b), "%02x", p[i]); s += b; }
  return s;
}

// ---------- anchor: the stub against RFC 3610 vector #1 ----------

static void test_stub_anchor() {
  // RFC 3610, Test Vector #1 (7-byte nonce, 4-byte tag, AAD present) —
  // the same published vector test_lora_psk.py anchors aes_ccm.py to.
  const uint8_t key[16] = {0x40,0x41,0x42,0x43,0x44,0x45,0x46,0x47,
                           0x48,0x49,0x4a,0x4b,0x4c,0x4d,0x4e,0x4f};
  const uint8_t nonce[7] = {0x10,0x11,0x12,0x13,0x14,0x15,0x16};
  const uint8_t aad[8] = {0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07};
  const uint8_t pt[4] = {0x20,0x21,0x22,0x23};
  const char *want = "7162015b4dac255d";  // ciphertext || tag
  mbedtls_ccm_context ctx;
  mbedtls_ccm_init(&ctx);
  int rc = mbedtls_ccm_setkey(&ctx, MBEDTLS_CIPHER_ID_AES, key, 128);
  CHECK(rc == 0, "stub setkey rc=%d", rc);
  uint8_t ct[4], tag[4];
  rc = mbedtls_ccm_encrypt_and_tag(&ctx, 4, nonce, 7, aad, 8, pt, ct, tag, 4);
  mbedtls_ccm_free(&ctx);
  CHECK(rc == 0, "stub encrypt rc=%d", rc);
  uint8_t joined[8];
  memcpy(joined, ct, 4); memcpy(joined + 4, tag, 4);
  CHECK(hexOf(joined, 8) == want, "stub RFC3610: got %s want %s",
        hexOf(joined, 8).c_str(), want);
  // and back again
  mbedtls_ccm_init(&ctx);
  mbedtls_ccm_setkey(&ctx, MBEDTLS_CIPHER_ID_AES, key, 128);
  uint8_t back[4];
  rc = mbedtls_ccm_auth_decrypt(&ctx, 4, nonce, 7, aad, 8, ct, back, tag, 4);
  mbedtls_ccm_free(&ctx);
  CHECK(rc == 0 && memcmp(back, pt, 4) == 0, "stub RFC3610 decrypt rc=%d", rc);
}

// ---------- codec vectors through the REAL header ----------

struct Vec {
  std::string name;
  long frameCtr;
  std::vector<uint8_t> plain22, wire34;
};

int main(int argc, char **argv) {
  const char *path = argc > 1 ? argv[1] : "lora_psk_vectors.json";
  std::string doc = slurp(path);

  std::vector<uint8_t> psk = unhex(jsonStr(doc, "psk_hex"));
  CHECK(psk.size() == 16, "psk_hex must decode to 16 bytes");
  long bootCtr = jsonInt(doc, "boot_ctr");
  CHECK(bootCtr >= 0, "boot_ctr missing");

  std::vector<Vec> vecs;
  for (size_t pos = 0;;) {
    size_t k = doc.find("\"plain22_hex\"", pos);
    if (k == std::string::npos) break;
    Vec v;
    v.plain22 = unhex(jsonStr(doc, "plain22_hex", k));
    v.wire34 = unhex(jsonStr(doc, "wire34_hex", k));
    size_t nk = doc.rfind("\"name\"", k);
    v.name = nk == std::string::npos ? "?" : jsonStr(doc, "name", nk);
    size_t fk = doc.rfind("\"frame_ctr\"", k);
    v.frameCtr = fk == std::string::npos ? -1 : jsonInt(doc, "frame_ctr", fk);
    vecs.push_back(v);
    pos = k + 1;
  }
  CHECK(vecs.size() >= 2, "expected >=2 vectors, found %zu", vecs.size());

  test_stub_anchor();

  const uint8_t wrongPsk[16] = {0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,
                                0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f};

  for (const Vec &v : vecs) {
    CHECK(v.plain22.size() == shepherd_psk::V1_LEN, "%s: plain22 len", v.name.c_str());
    CHECK(v.wire34.size() == shepherd_psk::WIRE_LEN, "%s: wire34 len", v.name.c_str());

    // wrap() reproduces the frozen wire packet byte for byte
    uint8_t wire[shepherd_psk::WIRE_LEN];
    bool ok = shepherd_psk::wrap(psk.data(), (uint32_t)bootCtr, (uint32_t)v.frameCtr,
                                 v.plain22.data(), wire);
    CHECK(ok, "%s: wrap() returned false", v.name.c_str());
    CHECK(memcmp(wire, v.wire34.data(), shepherd_psk::WIRE_LEN) == 0,
          "%s: wrap() mismatch\n  got  %s\n  want %s", v.name.c_str(),
          hexOf(wire, shepherd_psk::WIRE_LEN).c_str(),
          hexOf(v.wire34.data(), v.wire34.size()).c_str());

    // unwrap() accepts and rebuildV1() reproduces the frozen v1 packet
    uint8_t plain21[shepherd_psk::PAYLOAD_LEN];
    ok = shepherd_psk::unwrap(psk.data(), v.wire34.data(), plain21);
    CHECK(ok, "%s: unwrap() rejected the frozen vector", v.name.c_str());
    uint8_t rebuilt[shepherd_psk::V1_LEN];
    shepherd_psk::rebuildV1(plain21, rebuilt);
    CHECK(memcmp(rebuilt, v.plain22.data(), shepherd_psk::V1_LEN) == 0,
          "%s: rebuildV1() mismatch", v.name.c_str());

    // wrong PSK must fail the tag check
    uint8_t junk[shepherd_psk::PAYLOAD_LEN];
    CHECK(!shepherd_psk::unwrap(wrongPsk, v.wire34.data(), junk),
          "%s: unwrap() accepted a wrong PSK", v.name.c_str());

    // single-bit tampering must fail: schema byte (AAD), nonce,
    // ciphertext (first/last), tag
    for (size_t off : {0u, 5u, 9u, 29u, 33u}) {
      uint8_t bad[shepherd_psk::WIRE_LEN];
      memcpy(bad, v.wire34.data(), shepherd_psk::WIRE_LEN);
      bad[off] ^= 0x40;
      CHECK(!shepherd_psk::unwrap(psk.data(), bad, junk),
            "%s: unwrap() accepted tamper at offset %zu", v.name.c_str(), off);
    }
  }

  // Counter sensitivity: same payload, next frame_ctr -> different
  // wire bytes (nonce actually feeds the cipher), and it round-trips.
  if (!vecs.empty()) {
    const Vec &v = vecs[0];
    uint8_t w2[shepherd_psk::WIRE_LEN], p2[shepherd_psk::PAYLOAD_LEN];
    CHECK(shepherd_psk::wrap(psk.data(), (uint32_t)bootCtr, (uint32_t)v.frameCtr + 1,
                             v.plain22.data(), w2),
          "counter+1 wrap failed");
    CHECK(memcmp(w2, v.wire34.data(), shepherd_psk::WIRE_LEN) != 0,
          "counter+1 wire identical to frozen vector (nonce not used?)");
    CHECK(shepherd_psk::unwrap(psk.data(), w2, p2) &&
          memcmp(p2, v.plain22.data() + 1, shepherd_psk::PAYLOAD_LEN) == 0,
          "counter+1 round-trip failed");
  }

  if (failures == 0) {
    printf("PASS: %d checks, %zu vectors, real shared header vs frozen vectors\n",
           checks, vecs.size());
    return 0;
  }
  printf("FAILED: %d of %d checks failed\n", failures, checks);
  return 1;
}
