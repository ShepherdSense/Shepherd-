#!/usr/bin/env python3
"""Generate lora_psk_vectors.json — the shared codec v1/v2 test vectors.

Run:  python3 make_vectors.py
The vectors use a published, TEST-ONLY PSK (the FIPS-197 example key
pattern). It is not, and must never become, a deployment key.

Field values are chosen to be unambiguous under both float32 (ESP32)
and float64 formatting at the printed precision, so the expected
gateway JSON strings are exact.
"""

import json
import os

from gateway_model import Gateway, encode_beacon, encode_event, wrap_psk

HERE = os.path.dirname(os.path.abspath(__file__))

TEST_PSK = bytes.fromhex("000102030405060708090a0b0c0d0e0f")
BOOT_CTR = 7

# Field values (raw codec integers, as the node encoders take them).
BEACON = dict(
    suffix=0xA3F1, uptime_s=3661, ev_count=42,
    lat_e6=35125000, lon_e6=-78937500,   # 35.125000, -78.937500 (exact in binary)
    flags=0x03, fps=4, vbat_mv=3900,
)
EVENT = dict(
    suffix=0xA3F1, t0=123456, t_us=123456789012345,
    dur_s100=1234, depth_db10=123, cls=1, conf100=87, sensor=0,
)


def main():
    beacon22 = encode_beacon(**BEACON)
    event22 = encode_event(**EVENT)
    beacon_wire = wrap_psk(TEST_PSK, beacon22, BOOT_CTR, 100)
    event_wire = wrap_psk(TEST_PSK, event22, BOOT_CTR, 101)

    gw = Gateway(psk=TEST_PSK)
    beacon_json = gw.handle(beacon_wire)
    event_json = gw.handle(event_wire)
    assert len(beacon_json) == 1 and len(event_json) == 1

    vectors = {
        "comment": (
            "Shepherd LoRa codec v1/v2 shared test vectors. Generated by "
            "make_vectors.py. TEST-ONLY PSK — never deploy with it. "
            "plain22 is the full v1 packet (schema byte 1 + payload); "
            "wire34 is the v2 packet (schema byte 2 + nonce + AES-128-CCM "
            "ciphertext + 4-byte tag, AAD = the schema byte 0x02)."
        ),
        "psk_hex": TEST_PSK.hex(),
        "boot_ctr": BOOT_CTR,
        "vectors": [
            {
                "name": "beacon_psk",
                "kind": "beacon",
                "fields": {k: v for k, v in BEACON.items()},
                "frame_ctr": 100,
                "plain22_hex": beacon22.hex(),
                "wire34_hex": beacon_wire.hex(),
                "expected_gateway_json": beacon_json[0],
            },
            {
                "name": "event_psk",
                "kind": "event",
                "fields": {k: v for k, v in EVENT.items()},
                "frame_ctr": 101,
                "plain22_hex": event22.hex(),
                "wire34_hex": event_wire.hex(),
                "expected_gateway_json": event_json[0],
            },
        ],
    }
    out = os.path.join(HERE, "lora_psk_vectors.json")
    with open(out, "w") as f:
        json.dump(vectors, f, indent=2)
        f.write("\n")
    print("wrote", out)
    for v in vectors["vectors"]:
        print(v["name"], "plain22:", v["plain22_hex"])
        print(v["name"], "wire34 :", v["wire34_hex"])
        print(v["name"], "json   :", v["expected_gateway_json"])


if __name__ == "__main__":
    main()
